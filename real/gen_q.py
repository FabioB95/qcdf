"""Thinning law for LNS sub-solvers: tokens, table and figure (fire: lnsq.json, astro: ../astro/lnsq_astro.json)."""
import json, numpy as np, pandas as pd
from scipy.stats import binom
EPS, TOL = 0.001, 0.001
recs = json.load(open('lnsq.json')) + json.load(open('../astro/lnsq_astro.json'))

def thin(tr, B, q):
    n = np.arange(B + 1); return float((binom.pmf(n, B, q) * tr).sum())

rows, cfg = [], []
for r in recs:
    A = r['arms']; B = len(A['exact'][0]['gap']); dom = r.get('domain', 'fire')
    g = np.mean([x['gap'] for x in A['exact']], 0); tr = np.r_[r['gap0'], g]
    ex = g[-1]; uni = np.mean([x['gap'][-1] for x in A['uniform']])
    dimF = np.mean([np.mean(x['dimF']) for x in A['exact'] if x['dimF']])
    inform = uni - ex > 0.002
    n_eps = int(np.argmax(tr <= ex + EPS))

    lo, hi = 1e-4, 1.0
    for _ in range(40):
        m = (lo + hi) / 2
        if thin(tr, B, m) - ex <= EPS: hi = m
        else: lo = m
    qth = hi
    obs = {}
    for a in A:
        if a.startswith('q'): obs[float(a[1:])] = np.mean([x['gap'][-1] for x in A[a]]) - ex
    qgrid = sorted(obs); qobs = next((q for q in qgrid if obs[q] <= EPS), None)
    cfg.append(dict(dom=dom, T0=r.get('T0', ''), K=r['K'], w=r['w'], S=r['S'], dimF=dimF, inform=inform, B=B, n_eps=n_eps,
                    q_formula=n_eps / B, q_thin=qth, q_obs=qobs, ex=ex, uni_ex=uni - ex))
    for q, eo in obs.items():
        rows.append(dict(dom=dom, K=r['K'], w=r['w'], S=r['S'], q=q, eo=eo, et=thin(tr, B, q) - ex, inform=inform))
C = pd.DataFrame(cfg); R = pd.DataFrame(rows)
I = C[C.inform]; RI = R[R.inform]
covered = float((RI.eo <= RI.et + TOL).mean())

grid = sorted(R.q.unique())
I = I.assign(q_thin_grid=[next((q for q in grid if q >= x), 1.0) for x in I.q_thin])
agree = float((I.q_thin_grid >= I.q_obs.fillna(1.0)).mean())
exact_match = float((I.q_thin_grid == I.q_obs.fillna(1.0)).mean())
print(I[['dom', 'K', 'w', 'S', 'dimF', 'n_eps', 'q_formula', 'q_thin', 'q_thin_grid', 'q_obs', 'uni_ex']].round(4).to_string())

L = json.load(open('lns.json'))
po_q = np.mean([np.mean(r['arms']['qaoa']['popt']) for r in L]); po_u = np.mean([np.mean(r['arms']['uniform']['popt']) for r in L])
A_meas = po_q / po_u
qstar = float(I.q_thin.median())
F_uni = 128 / -np.log(1 - qstar); F_qaoa = A_meas * F_uni
tok = dict(XQ_ncfg=str(len(C)), XQ_ninf=str(len(I)), XQ_cover=f"{100*covered:.0f}", XQ_agree=f"{100*agree:.0f}", XQ_match=f"{100*exact_match:.0f}",
           XQ_nrows=str(len(RI)), XQ_qmax=f"{I.q_obs.max():g}", XQ_qstar=f"{qstar:.2f}", XQ_Funi=f"{F_uni:,.0f}".replace(',', '{,}'),
           XQ_Fqaoa=f"{F_qaoa:,.0f}".replace(',', '{,}'), XQ_Ameas=f"{A_meas:.1f}",
           XQ_qminf=f"{I.q_thin.min():.2f}", XQ_qmaxf=f"{I.q_thin.max():.2f}")

rho_rows = []
for r in recs:
    A = r['arms']; p = np.nanmean([x['p'] for x in A['exact'] if x['p'] is not None]); u = np.nanmean([x['u'] for x in A['exact'] if x['u'] is not None])
    dimF = np.mean([np.mean(x['dimF']) for x in A['exact'] if x['dimF']]); rho_rows.append(dict(ratio=dimF / r['S'], rho=u / p if p > 0 else np.nan))
RR = pd.DataFrame(rho_rows)
tok['XQ_rho_lo'] = f"{RR[RR.ratio < 1].rho.mean():.2f}"; tok['XQ_rho_hi'] = f"{RR[RR.ratio > 50].rho.mean():.2f}"
json.dump(tok, open('q_tokens.json', 'w'), indent=1)

def pts(dom, col):
    X = RI[RI.dom == dom]
    return f"\\addplot[only marks,mark=*,mark size=1.3pt,{col},fill opacity=0.6,draw opacity=0.8] coordinates {{" + \
        " ".join(f"({100*a:.3f},{100*b:.3f})" for a, b in zip(X.et, X.eo)) + "};"
mx = 100 * max(RI.et.max(), RI.eo.max()) * 1.05
Fs = np.logspace(1, 5, 30)
line = lambda S, q: " ".join(f"({F:.1f},{max(1.0, F * -np.log(1 - q) / S):.3f})" for F in Fs)
fig = r"""% thinning law, generated by real/gen_q.py
\begin{tikzpicture}
\begin{groupplot}[group style={group size=2 by 1,horizontal sep=1.7cm},height=5cm,width=0.48\linewidth,grid=major,grid style={gray!20},title style={font=\small},label style={font=\small},tick label style={font=\scriptsize}]
\nextgroupplot[xmin=0,ymin=0,xmax=""" + f"{mx:.2f}" + r""",ymax=""" + f"{mx:.2f}" + r""",xlabel={thinning prediction (\% above exact LNS)},ylabel={observed (\% above exact LNS)},title={(a) degradation by $q$-sub-solver},legend style={font=\scriptsize,at={(0.03,0.97)},anchor=north west}]
""" + pts('fire', 'qsel') + "\n\\addlegendentry{wildfire}\n" + pts('astro', 'qblue') + "\n\\addlegendentry{sky}\n" + \
r"""\addplot[gray,dashed,domain=0:""" + f"{mx:.2f}" + r"""] {x};
\nextgroupplot[xmode=log,ymode=log,xlabel={window subspace $|\mathcal{F}_{k}(W)|$},ylabel={required amplification $A^\ast$},title={(b) design rule},legend style={font=\scriptsize,at={(0.03,0.97)},anchor=north west}]
\addplot[qsel,thick] coordinates {""" + line(16, 0.3) + r"""};\addlegendentry{$S{=}16$, $q^\ast{=}0.3$}
\addplot[qsel,dashed] coordinates {""" + line(128, 0.3) + r"""};\addlegendentry{$S{=}128$, $q^\ast{=}0.3$}
\addplot[qblue,dashed] coordinates {""" + line(128, 0.1) + r"""};\addlegendentry{$S{=}128$, $q^\ast{=}0.1$}
\addplot[black,thick,densely dotted] coordinates {(10,""" + f"{A_meas:.2f}" + r""") (100000,""" + f"{A_meas:.2f}" + r""")};\addlegendentry{QAOA $p{=}3$, measured}
\end{groupplot}
\end{tikzpicture}
"""
open('../paper/figures/tikz/qthin.tex', 'w').write(fig)
fn = '../paper/v4_body_filled.tex'; s = open(fn).read()
for k_, v in sorted(tok.items(), key=lambda kv: -len(kv[0])): s = s.replace('@@' + k_ + '@@', v)
open(fn, 'w').write(s)
print(tok)
